// Respaldo con la clase de Data Dragon cuando el campeón no está en la lista.
const DDRAGON_TAG_FALLBACK = {
  Tank: 'Vanguard',
  Fighter: 'Diver',
  Assassin: 'Assassin',
  Mage: 'Burst',
  Marksman: 'Marksman',
  Support: 'Enchanter',
};

export function getChampionClasses(name, ddragonTags) {
  if (CHAMPION_CLASSES[name]) return { classes: CHAMPION_CLASSES[name], official: true };
  const mapped = (ddragonTags || []).map((t) => DDRAGON_TAG_FALLBACK[t]).filter(Boolean);
  return { classes: [...new Set(mapped)].slice(0, 2), official: false };
}

export function getChampionStyle(name, classes) {
  if (STYLE_OVERRIDES[name]) return STYLE_OVERRIDES[name];
  const [primary, secondary] = classes.map((c) => CLASS_INFO[c]?.style);
  // La clase primaria manda, salvo que sea "pick" y la secundaria sea más definida.
  if (primary === 'pick' && secondary && secondary !== 'pick') return secondary;
  return primary || null;
}
